def get_standard_by_code(code: str) -> dict[str, Any] | None:
    """Return a single standard entry by its ``code`` field, or None."""
    for std in PACK_CONFIG["standards"]:
        if std["code"] == code:
            return std
    return None


def get_classifications_summary() -> dict[str, Any]:
    """Compact summary of code+label across CFC/eBKP/NPK (no metadata).

    Suitable for autocomplete dropdowns or quick code lookup. Returns a
    dict keyed by catalog code, with each value a list of
    ``{code, label_fr, level}`` entries. Total payload typically <100 KB.
    """
    summary: dict[str, Any] = {}
    for std in PACK_CONFIG["standards"]:
        if std["code"] not in {"CFC", "eBKP-H", "eBKP-T", "NPK"}:
            continue
        summary[std["code"]] = [
            {
                "code": entry.get("code"),
                "label_fr": (entry.get("label") or {}).get("fr"),
                "level": entry.get("level"),
                "is_sipal_specific": entry.get("is_sipal_specific", False),
            }
            for entry in std.get("entries", [])
        ]
    return summary

def _load_classifications() -> dict[str, Any]:
    """Load the CFC/eBKP/NPK bundle generated by ``swiss-refdata`` exporter."""
    if not _CLASSIFICATIONS_PATH.exists():
        return {
            "schema_version": "1.0",
            "catalogs": {"CFC": [], "eBKP-H": [], "eBKP-T": [], "NPK": []},
            "keywords": [],
            "mappings": [],
            "legal_notice": "",
            "sipal_notice": "",
        }
    return json.loads(_CLASSIFICATIONS_PATH.read_text())


